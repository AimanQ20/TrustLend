// Usage: npx hardhat run scripts/gas-escrow.js      -> writes docs/gas-escrow.json and docs/GAS_ESCROW.md
const fs = require("fs");
const path = require("path");
const { measure } = require("./lib/gasEscrow");

const ROWS = [
  ["fund", "fund() - lender deposits (1st)  <- PRIMARY OPERATION", 0],
  ["fund", "fund() - lender deposits (3rd)", 2],
  ["releaseFunds", "releaseFunds() - borrower accepts (1st)", 0],
  ["releaseFunds", "releaseFunds() - borrower accepts (3rd)", 2],
  ["repay", "repay() - borrower repays (3rd)", 2],
  ["raiseDispute", "raiseDispute() - lender (1st)", 0],
  ["raiseDispute", "raiseDispute() - lender (3rd)", 2],
  ["resolveDispute", "resolveDispute() - arbiter refunds lender (3rd)", 2],
  ["withdraw", "withdraw() - borrower (balance written 1 -> 0)", 0],
];
const pct = (b, o) => `${(((o - b) / b) * 100).toFixed(1)}%`;

(async () => {
  const { baseline, optimized } = await measure();
  const json = (o) => JSON.parse(JSON.stringify(o, (_, v) => (typeof v === "bigint" ? v.toString() : v)));
  fs.writeFileSync(path.join(__dirname, "..", "docs", "gas-escrow.json"), JSON.stringify({ baseline: json(baseline), optimized: json(optimized) }, null, 2));
  let rows = "";
  for (const [k, label, i] of ROWS) {
    const b = Number(baseline[k][i]), o = Number(optimized[k][i]);
    rows += `| ${label} | ${b} | ${o} | ${b - o} | ${pct(b, o)} |\n`;
    console.log(label.padEnd(70), b, o, pct(b, o));
  }
  const md = `# Escrow gas evaluation (Member 3)

> Generated by \`npx hardhat run scripts/gas-escrow.js\`. Numbers are \`receipt.gasUsed\` from the in-process Hardhat network.
> Raw numbers: \`docs/gas-escrow.json\`.

## Methodology (so the comparison is fair)
- **Baseline** = \`contracts/gas/EscrowBaseline.sol\`: the straightforward first draft, recorded BEFORE optimizing.
  Same logic, same roles (\`onlyActiveRole\`), same events, same workflow calls, same reentrancy guard, same checks-effects-interactions order.
  Differences: \`struct { address lender; uint256 amount; uint8 status; }\` (3 storage slots) and \`require("string")\` errors.
- **Optimized** = \`contracts/EscrowDispute.sol\`, the final contract.
- Same compiler (solc 0.8.24), same optimizer (enabled, 200 runs), same signers, same call order, same inputs (1 ETH loans), fresh deployment of each (own Registry, CoreWorkflow and escrow).
- Each operation is run 3 times on different loans. The 1st run is the first write into fresh storage; the 3rd is steady state.
- Both contracts behave identically for these operations (same events/state results), verified by the escrow test-suite running the same flows.

## Results
| Operation | Baseline gas | Optimized gas | Saved | Change |
|---|---:|---:|---:|---:|
${rows}
> Deployment gas / bytecode are intentionally not compared (the final contract uses custom errors and a packed layout, so bytecode differs for reasons unrelated to the operations measured).

## Optimizations applied (what changed and why it is cheaper)
1. **Packed deposit struct: \`address lender\` (20 B) + \`uint88 amount\` (11 B) + \`Status status\` (1 B) = 32 B = ONE storage slot.**
   The baseline used 3 slots (address, uint256, uint8). \`fund()\` writes 1 slot instead of 3 (two fewer 22,100-gas zero-to-nonzero SSTOREs), and every later
   function reads/writes one slot instead of two or three (each extra cold SLOAD is 2,100 gas).
2. **Custom errors instead of \`require(cond, "string")\`.** Smaller bytecode and cheaper failing paths (4-byte selector instead of ABI-encoded string),
   and every revert reason is decodable from the ABI in the UI. Failing transactions are not measured by this harness, so this is NOT included in the percentages;
   it is listed as a justified hardening and efficiency choice.
3. **Single read-modify-write of the packed slot** for status changes (\`d.status = ...\` on a storage pointer touches the one slot).

## Trade-offs (honest)
| Change | Cost / risk |
|---|---|
| \`uint88\` amount | Maximum deposit about 309 million ETH. \`fund()\` rejects larger amounts (\`AmountTooLarge\`), so there is no silent truncation. |
| Packing | Struct layout becomes part of the contract. Reordering fields later would corrupt storage in an upgradeable setup (this project is non-upgradeable). |
| Custom errors | Less readable in raw revert data; the ABI decodes them (ethers v6, the frontend does). |
| Reentrancy guard kept | The guard costs about 2 storage writes per call (the lock goes 1 -> 2 -> 1 inside one transaction, which is cheap thanks to refunds), but is kept in BOTH versions and is never removed for gas. Security is not traded for gas. |

## Security note
The optimization does not weaken any check: both contracts run the same authorization, status, amount and ownership checks. The escrow negative tests and the reentrancy attack test run against the optimized contract.
`;
  fs.writeFileSync(path.join(__dirname, "..", "docs", "GAS_ESCROW.md"), md);
})().catch((e) => { console.error(e); process.exitCode = 1; });
