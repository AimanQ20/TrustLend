// Usage: npx hardhat run scripts/gas-report.js     -> writes docs/GAS_REGISTRY.md + docs/gas-registry.json
const fs = require("fs");
const path = require("path");
const { measure } = require("./lib/gasMeasure");

const pct = (b, o) => (((Number(o) - Number(b)) / Number(b)) * 100).toFixed(1) + "%";
const row = (name, b, o) => `| ${name} | ${b} | ${o} | ${Number(b) - Number(o)} | ${pct(b, o)} |`;

async function main() {
  const { baseline: b, optimized: o } = await measure();
  const ops = [
    ["register() - new wallet", "register"],
    ["assignRole() - add role to existing user", "assignExisting"],
    ["assignRole() - create new staff wallet", "assignStaff"],
  ];

  let table = "| Operation (occurrence) | Baseline gas | Optimized gas | Saved | Change |\n|---|---:|---:|---:|---:|\n";
  for (const [label, key] of ops) {
    table += row(`${label} - 1st (first member of role)`, b[key][0], o[key][0]) + "\n";
    table += row(`${label} - 3rd (steady state)`, b[key][2], o[key][2]) + "\n";
  }
  const dep = `| Deployment gas | ${b.deployGas} | ${o.deployGas} | ${Number(b.deployGas) - Number(o.deployGas)} | ${pct(b.deployGas, o.deployGas)} |`;
  const size = `| Runtime bytecode (bytes) | ${b.runtimeBytes} | ${o.runtimeBytes} | ${b.runtimeBytes - o.runtimeBytes} | ${pct(b.runtimeBytes, o.runtimeBytes)} |`;

  const md = `# Registry gas evaluation (Member 1)

> Generated by \`npx hardhat run scripts/gas-report.js\`. Numbers are \`receipt.gasUsed\` from the in-process Hardhat network.

## Methodology (so the comparison is fair)
- **Baseline** = \`contracts/gas/RegistryBaseline.sol\`: the straightforward first draft, in the style of OpenZeppelin \`AccessControlEnumerable\`
  (per-role boolean mapping, on-chain member list per role, unpacked \`uint256\` fields, role counter, \`require("string")\` errors).
- **Optimized** = \`contracts/Registry.sol\`, the final contract.
- Same compiler (solc 0.8.24), same optimizer (enabled, 200 runs), same signers, same call order and inputs, fresh deployment of each.
- Each operation is run 3 times on different wallets. The **1st** run is the worst case for the baseline (the first push into an empty
  array costs a zero-to-nonzero SSTORE); the **3rd** run is steady state. Both are reported.
- Baseline and optimized behave identically for these operations (same checks, same events), verified by the test-suite.

## Results
${table}
> **Deployment gas / bytecode are intentionally NOT compared.** The final Registry has far more features than the baseline
> (pause, suspend/reinstate, two-step admin, views), so it is larger: deployment gas ${o.deployGas} vs ${b.deployGas}, runtime ${o.runtimeBytes} B vs ${b.runtimeBytes} B.
> Comparing those would not be like-for-like. The comparison above covers only the three operations both contracts implement identically.

## Optimizations applied (what changed and why it is cheaper)
1. **Packed bit-flag roles in the user's profile slot, instead of \`mapping(bytes32 => mapping(address => bool))\`.**
   All 6 roles are 1 bit each in a \`uint8\` that shares one 32-byte storage slot with \`status\`, \`registeredAt\` and \`verifiedAt\`.
   Granting a role is one read-modify-write of an already-loaded slot (SSTORE reset, about 2,900 gas) instead of a new boolean slot
   (SSTORE zero-to-nonzero, 20,000 gas + cold access) plus a role counter update.
2. **Removed the on-chain member array** (\`roleMembers[role].push(user)\`). That push writes the array length and the new element
   (two more storage writes). Enumeration is not needed on-chain: every grant emits an indexed \`RoleGranted\` event, and the off-chain
   role-lookup service rebuilds "who holds role X" from logs for free.
3. **Custom errors instead of \`require(cond, "long string")\`, and one cached storage read per call (\`Status s = p.status\`).**
   Custom errors make each failing check cheaper (4-byte selector instead of an ABI-encoded string) and keep every revert reason
   in the ABI. This harness measures only successful transactions, so this change is **not** part of the percentages above; it is
   listed as a justified, low-cost hardening/efficiency choice, not as a measured saving.

## Trade-offs (honest)
| Change | Cost / risk |
|---|---|
| Bit-flag roles | Maximum 8 roles (6 used). ABI is not OpenZeppelin-compatible (\`hasRole(address,uint8)\`). A new role needs a new bit and a contract change. Packing makes the struct layout part of the contract's "API"; reordering fields later would corrupt storage in an upgradeable setup (this project is non-upgradeable). |
| No on-chain enumeration | A contract cannot loop over "all verifiers" on-chain. Anything that needs the list must use events/an indexer (that is the project's hybrid design anyway). |
| Custom errors | Slightly less readable than strings for people who only read raw revert data; the ABI decodes them (ethers v6 and the frontend do). |
| Readability | Bit masks are less self-explanatory than named mappings; mitigated with the \`Roles\` library constants and NatSpec. |

## Security note
The optimization does **not** weaken access control: the same checks run in both versions, and the full negative test-suite
(\`test/Registry.access.test.js\`) plus the randomised invariants test run against the optimized contract.
`;

  fs.writeFileSync(path.join(__dirname, "..", "docs", "GAS_REGISTRY.md"), md);
  const ser = (x) => JSON.parse(JSON.stringify(x, (_, v) => (typeof v === "bigint" ? v.toString() : v)));
  fs.writeFileSync(path.join(__dirname, "..", "docs", "gas-registry.json"), JSON.stringify(ser({ baseline: b, optimized: o }), null, 2));
  console.log(table);
}
main().catch((e) => { console.error(e); process.exit(1); });
